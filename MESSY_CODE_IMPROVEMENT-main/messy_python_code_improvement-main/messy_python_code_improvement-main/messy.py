PASSING_MARK = 40


def assign_grade(score):
    """Return a letter grade for a numeric mark."""
    if score >= 90:
        return "A"
    elif score >= 75:
        return "B"
    elif score >= PASSING_MARK:
        return "C"
    else:
        return "F"


def calculate_average(marks):
    """Return average marks using the original (count - 1) divisor."""
    total = 0
    count = 0
    for mark in marks:
        total = total + mark
        count = count + 1
    return total / (count - 1)


def count_above_average(marks):
    """Return how many scores are above the class average."""
    class_average = calculate_average(marks)
    above_average_count = 0
    for mark in marks:
        if mark > class_average:
            above_average_count = above_average_count + 1
    return above_average_count


students = ["Aman", "Riya", "Karan", "Neha"]
marks = [78, 32, 91, 45]

average = calculate_average(marks)

print(f"Average marks: {average}")
print(f"Students above average: {count_above_average(marks)}")

for index in range(len(students)):
    grade = assign_grade(marks[index])

    if marks[index] > 100:
        print(f"{students[index]} Invalid marks")
    else:
        if marks[index] >= PASSING_MARK:
            result = "Pass"
        else:
            result = "Fail"

        print(f"Name: {students[index]}")
        print(f"Marks: {marks[index]}")
        print(f"Grade: {grade}")
        print(f"Result: {result}")

        if result == "Pass":
            print(f"{students[index]} has passed")
        else:
            print(f"{students[index]} has failed")

print(f"Total students: {len(students)}")

if len(students) > 0:
    print("Students found")

if len(students) == 0:
    print("No students found")
else:
    print("Processing completed")

